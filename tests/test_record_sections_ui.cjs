async function checkFighterFeed() {
  const badge = {textContent:'Active'};
  const body = {innerHTML:''};
  const signal = {textContent:'Live'};
  const panel = {isConnected:true, hidden:false, dataset:{}, closest:()=>({querySelector:()=>badge}),
    querySelector:selector=>selector==='.mind-preview-body'?body:signal};
  ctx.panel = panel;
  ctx.fighter = {id:36,name:'Mara Kel',status:'Active',mind:[]};
  ctx.api = async path => {
    assert.equal(path,'/api/fighters/36/mind');
    return ctx.fighter;
  };
  run("app.querySelector=()=>panel; currentDetail={type:'fighter',id:36}");
  await run('refreshFighterMind()');
  assert.match(body.innerHTML,/Give me a moment to gather my thoughts/);
  ctx.fighter.mind_status={narration_mode:'sensory'};
  await run('refreshFighterMind()');
  assert.match(body.innerHTML,/Stillness\. Listening\./);
  ctx.fighter.mind_status={narration_mode:'task_log'};
  await run('refreshFighterMind()');
  assert.match(body.innerHTML,/PROCESSING INPUT \/\/ RESPONSE PENDING/);
  ctx.fighter.mind = [{content:'Pending text.',writer_status:'paused'},{content:'The gate is closed. I should check the seal.',writer_status:'ready',memory_id:'new'}];
  await run('refreshFighterMind()');
  assert.match(body.innerHTML,/#memory-new[^>]*>The gate is closed\.<\/a>/);
  assert.doesNotMatch(body.innerHTML,/Pending text|I should check/);
  ctx.fighter.mind.push(...['The seal is intact.','The relief is late.','Fourth thought.'].map(content=>({content,writer_status:'ready'})));
  await run('refreshFighterMind()');
  assert.equal((body.innerHTML.match(/<p>/g)||[]).length,3);
  assert.match(body.innerHTML,/<p>The seal is intact\.<\/p><p>The relief is late\.<\/p>$/);
  ctx.api = async () => { throw Error('Unavailable'); };
  await run('refreshFighterMind()');
  assert.equal(panel.dataset.signal,'offline');
  ctx.fighter.status = 'Killed';
  ctx.api = async () => ctx.fighter;
  await run('refreshFighterMind()');
  assert.equal(badge.textContent,'Killed');
  assert.equal(panel.hidden,true);
  assert.equal(body.innerHTML,'');
}
checkFighterFeed().catch(error => { console.error(error); process.exitCode=1; });
